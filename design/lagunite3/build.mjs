// Compiles Lagunite 3 (tokens.json + components.css) into one stylesheet.
// Usage: node design/lagunite3/build.mjs [outFile]   (default: pocs/builder/skins/lagunite3.css)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const out = process.argv[2] ?? path.join(here, '../../pocs/builder/skins/lagunite3.css');
const tokens = JSON.parse(fs.readFileSync(path.join(here, 'tokens.json'), 'utf8'));
const components = fs.readFileSync(path.join(here, 'components.css'), 'utf8');

const value = (v, theme) => {
  const s = typeof v === 'object' ? (v[theme] ?? v.light) : v;
  return s.startsWith('{') ? `var(--${s.slice(1, -1)})` : s;
};
const decls = (list, theme) => list.map((t) => `  --${t.name}: ${value(t.value, theme)};`).join('\n');
const themed = [...tokens.color.tokens, ...tokens.shadow.tokens];
const plain = ['spacing', 'radius', 'blur', 'borderWidth', 'breakpoint'].flatMap((f) => tokens[f]?.tokens ?? []);
const families = Object.entries(tokens.type.families).map(([k, stack]) => `  --font-${k}: ${stack};`).join('\n');

const typeClasses = tokens.type.groups.flatMap((g) => g.styles.map((s) => {
  const props = [
    `font-family: var(--font-${s.family ?? g.family})`,
    `font-size: ${s.fontSize}`,
    `line-height: ${s.lineHeight}`,
    `font-weight: ${s.fontWeight}`,
    s.letterSpacing && `letter-spacing: ${s.letterSpacing}`,
  ].filter(Boolean);
  return `.${s.name} { ${props.join('; ')}; }`;
})).join('\n');

// @import must stay first in the output, so lift it out of components.css.
const importLine = components.match(/@import url\([^)]*\);/)?.[0] ?? '';
const body = components.replace(importLine, '').trimStart();

const css = `${importLine}
/* Lagunite 3 — generated by design/lagunite3/build.mjs from tokens.json + components.css. Do not edit. */

:root, [data-theme="light"] {
${decls(themed, 'light')}
}

[data-theme="dark"], .night {
${decls(themed, 'dark')}
  color-scheme: dark;
}

:root {
${decls(plain, 'light')}
${families}
}

${typeClasses}

${body}`;

fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, css);
console.log(`wrote ${path.relative(process.cwd(), out)} (${css.length} bytes)`);
